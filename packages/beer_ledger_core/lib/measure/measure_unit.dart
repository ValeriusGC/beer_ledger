import 'measure_family.dart';

/// Контракт единицы измерения одной оси учёта.
///
/// Реализуется enum-семействами (`VolumeUnit`, `MassUnit`, `MoneyUnit`,
/// `LengthUnit`, `EnergyUnit`, `CountUnit`). Набор единиц каждого семейства
/// **замкнут языком**: enum нельзя дополнить извне, поэтому подделать
/// коэффициент известной единицы невозможно, а `switch` по единицам семейства
/// проверяется на полноту компилятором.
///
/// Значение переводится между единицами одного [family] по формуле:
///
/// ```dart
/// final inTarget = value * from.ratioToBase / to.ratioToBase;
/// ```
///
/// Пример — 0.5 л в миллилитрах:
///
/// ```dart
/// const from = VolumeUnit.liter;
/// const to = VolumeUnit.milliliter;
/// final ml = 0.5 * from.ratioToBase / to.ratioToBase; // 500.0
/// ```
///
/// Интерфейс, а не базовый класс, потому что enum умеет только `implements`.
/// Замкнутость набора при этом не теряется: она держится на уровне каждого
/// семейства — там, где она и нужна для конвертации.
abstract interface class MeasureUnit {
  /// Стабильный идентификатор для хранения и обмена данными.
  ///
  /// Формат — `<семейство>.<единица>`, например `volume.liter`. Не зависит от
  /// языка интерфейса и не меняется при правке [symbol], поэтому пригоден как
  /// ключ в БД и в экспорте. Префикс семейства делает идентификаторы
  /// уникальными в пределах всего пакета.
  ///
  /// Хранить **только** [id]: имя значения enum и его `index` — детали кода,
  /// переименование или перестановка значений не должны портить записи.
  String get id;

  /// Короткая подпись для интерфейса: `L`, `kg`, `₽`.
  ///
  /// Названа не `name`, потому что `name` у enum занято языком
  /// (`EnumName.name` возвращает исходный идентификатор значения). В iter 1.1
  /// подписи латинские и не локализованы: домен не знает о языке приложения.
  String get symbol;

  /// Множитель к базовой единице [family].
  ///
  /// У базовой единицы равен `1`. Например база массы — грамм, поэтому у
  /// килограмма коэффициент `1000`, а у фунта — `453.59237`.
  double get ratioToBase;

  /// Семейство, внутри которого допустима конвертация.
  MeasureFamily get family;
}
