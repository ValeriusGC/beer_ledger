/// Семейство единиц измерения — область, внутри которой конвертация осмысленна.
///
/// Переводить значение допустимо только между единицами **одного** семейства:
/// литры в килограммы или порции в килокалории — нельзя. Проверка совместимости
/// выполняется сравнением `MeasureUnit.family`, а не типов времени выполнения,
/// поэтому она остаётся корректной при добавлении новых единиц и семейств.
///
/// В каждом семействе есть базовая единица с коэффициентом `1`
/// (`baseUnit` у соответствующего enum); коэффициенты остальных единиц выражены
/// относительно неё.
enum MeasureFamily {
  /// Объём. База — миллилитр (он же кубический сантиметр).
  volume,

  /// Масса. База — грамм.
  mass,

  /// Деньги. База — минорная единица валюты (копейка).
  money,

  /// Длина. База — метр.
  length,

  /// Энергия. База — калория.
  energy,

  /// Безразмерный счёт: тапы, порции, баллы. Конвертация внутри семейства —
  /// тождественная: единицы различаются только подписью в интерфейсе.
  count,
}
